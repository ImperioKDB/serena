create extension if not exists pgcrypto;

create table if not exists public.research_tasks (
  id uuid primary key default gen_random_uuid(),
  request_text text not null,
  status text not null default 'queued' check (status in ('queued', 'running', 'completed', 'failed')),
  input_json jsonb not null default '{}'::jsonb,
  result_json jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz
);

create index if not exists research_tasks_status_created_at_idx
  on public.research_tasks (status, created_at desc);

create table if not exists public.execution_events (
  id bigint generated by default as identity primary key,
  task_id uuid not null references public.research_tasks (id) on delete cascade,
  sequence_number integer not null,
  event_type text not null,
  payload_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (task_id, sequence_number)
);

create index if not exists execution_events_task_id_created_at_idx
  on public.execution_events (task_id, created_at);
